create table public.fixture_current_identity(release_id uuid primary key,allowed boolean not null,calls integer not null default 0);
-- External validator contract stub: current evidence may disagree with a
-- previously checked release JSON. The publisher must call this under locks.
create function supplier_price_validation_internal.check_publication_identity(
  input_release_id uuid,input_organization_id uuid,input_supplier_id uuid,input_brand_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_allowed boolean; v_audit jsonb;
begin
  update public.fixture_current_identity set calls=calls+1 where release_id=input_release_id returning allowed into v_allowed;
  v_audit:=jsonb_build_object('policy','cross-brand-v1','checked',true,'review_required',not coalesce(v_allowed,false));
  update public.supplier_price_releases set brand_identity_audit=v_audit,
    error_code=case when v_allowed then null else 'CROSS_BRAND_BULK_OVERLAP' end where id=input_release_id;
  return jsonb_build_object('status',case when v_allowed then 'identity_checked' else 'review_required' end,
    'publication_allowed',coalesce(v_allowed,false),'error_code',case when v_allowed then null else 'CROSS_BRAND_BULK_OVERLAP' end,
    'brand_identity_audit',v_audit);
end;
$$;
revoke all on function supplier_price_validation_internal.check_publication_identity(uuid,uuid,uuid,uuid) from public,anon,authenticated,service_role;
